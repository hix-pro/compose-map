import type { Analysis, ComposeModel, Finding, Severity } from '../types'
import { buildGraph, NODE_HEIGHT, NODE_WIDTH } from './layout'

const PADDING = 48
const HEADER_HEIGHT = 96

const SEVERITY_LABEL: Record<Severity, string> = {
  critical: 'Critical',
  warning: 'Warning',
  info: 'Info',
}

const SEVERITY_COLOR: Record<Severity, string> = {
  critical: '#ff6b6b',
  warning: '#ffb454',
  info: '#7dd3fc',
}

function escapeXml(value: string): string {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;')
}

function escapeMarkdown(value: string): string {
  return value.replaceAll('|', '\\|').replace(/\n/g, ' ')
}

function escapeMermaid(value: string): string {
  return value
    .replaceAll('"', '#quot;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('\n', ' ')
}

function truncate(value: string, length: number): string {
  return value.length > length ? `${value.slice(0, length - 1)}…` : value
}

function modelName(model: ComposeModel): string {
  return model.name ?? model.sourceName?.replace(/\.ya?ml$/i, '') ?? 'compose stack'
}

function serviceCounts(findings: Finding[], service: string): Record<Severity, number> {
  const counts: Record<Severity, number> = { critical: 0, warning: 0, info: 0 }
  for (const finding of findings) {
    if (finding.service === service) counts[finding.severity] += 1
  }
  return counts
}

export function toMermaid(model: ComposeModel, findings: Finding[]): string {
  const ids = new Map<string, string>()
  model.services.forEach((service, index) => {
    ids.set(service.name, `s_${index}`)
  })

  const lines = ['flowchart LR', '  %% Generated by ComposeMap']
  lines.push(
    '  classDef critical fill:#2a1215,stroke:#ff6b6b,color:#f8fafc;',
    '  classDef warning fill:#2a1e10,stroke:#ffb454,color:#f8fafc;',
    '  classDef info fill:#0e2230,stroke:#7dd3fc,color:#f8fafc;',
    '  classDef clean fill:#101820,stroke:#3b4654,color:#f8fafc;',
  )

  for (const service of model.services) {
    const id = ids.get(service.name) ?? 's_unknown'
    const subtitle = service.image ?? (service.build ? 'built locally' : 'no image')
    const label = `${escapeMermaid(service.name)}<br/><small>${escapeMermaid(truncate(subtitle, 36))}</small>`
    const counts = serviceCounts(findings, service.name)
    const tone: Severity | 'clean' =
      counts.critical > 0
        ? 'critical'
        : counts.warning > 0
          ? 'warning'
          : counts.info > 0
            ? 'info'
            : 'clean'
    lines.push(`  ${id}["${label}"]:::${tone}`)
  }

  const linked = new Set<string>()
  for (const service of model.services) {
    for (const dependency of service.dependsOn) {
      const source = ids.get(service.name)
      const target = ids.get(dependency)
      if (!source || !target) continue
      const key = `${source}->${target}`
      if (linked.has(key)) continue
      linked.add(key)
      lines.push(`  ${source} -->|needs| ${target}`)
    }
  }

  return `${lines.join('\n')}\n`
}

export function toMarkdown(model: ComposeModel, analysis: Analysis): string {
  const lines = [
    `# ComposeMap report — ${escapeMarkdown(modelName(model))}`,
    '',
    '> Generated locally with [ComposeMap](https://github.com/hix-pro/compose-map). No file was uploaded.',
    '',
    '## Summary',
    '',
    '| Services | Published ports | Healthchecks | Bind mounts | Critical | Warnings | Info |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    `| ${analysis.stats.services} | ${analysis.stats.publishedPorts} | ${analysis.stats.healthchecks} | ${analysis.stats.bindMounts} | ${analysis.counts.critical} | ${analysis.counts.warning} | ${analysis.counts.info} |`,
    '',
    '## Services',
    '',
    '| Service | Image or build | Ports | Depends on | Healthcheck |',
    '| --- | --- | --- | --- | --- |',
  ]

  for (const service of model.services) {
    const ports = service.ports.map((port) => port.raw).join(', ') || '—'
    const dependencies = service.dependsOn.join(', ') || '—'
    const image = service.image ?? (service.build ? `build: ${service.build}` : '—')
    lines.push(
      `| \`${escapeMarkdown(service.name)}\` | ${escapeMarkdown(image)} | ${escapeMarkdown(ports)} | ${escapeMarkdown(dependencies)} | ${service.healthcheck ? 'yes' : 'no'} |`,
    )
  }

  lines.push('', '## Findings', '')

  if (analysis.findings.length === 0) {
    lines.push('No findings from the current rule set. This is not a security audit.')
  }

  for (const severity of ['critical', 'warning', 'info'] as const) {
    const group = analysis.findings.filter((finding) => finding.severity === severity)
    if (group.length === 0) continue
    lines.push(`### ${SEVERITY_LABEL[severity]} (${group.length})`, '')
    for (const finding of group) {
      const scope = finding.service ? ` — \`${escapeMarkdown(finding.service)}\`` : ''
      lines.push(`- **${escapeMarkdown(finding.title)}**${scope}`)
      lines.push(`  - ${escapeMarkdown(finding.detail)}`)
      lines.push(`  - **Fix:** ${escapeMarkdown(finding.fix)}`)
    }
    lines.push('')
  }

  return `${lines.join('\n').trim()}\n`
}

interface RenderOptions {
  includeHeader?: boolean
}

/**
 * Renders a standalone, deterministic SVG of the service graph. This is the
 * same layout used by the interactive canvas, so the export matches the app.
 */
export function toSvg(
  model: ComposeModel,
  findings: Finding[],
  options: RenderOptions = {},
): string {
  const { includeHeader = true } = options
  const graph = buildGraph(model, findings)

  if (graph.nodes.length === 0) {
    return '<svg xmlns="http://www.w3.org/2000/svg" width="480" height="160"><rect width="480" height="160" fill="#07090c"/><text x="24" y="88" fill="#8b98a9" font-family="Inter, sans-serif" font-size="14">No services to render.</text></svg>'
  }

  const xs = graph.nodes.map((node) => node.position.x)
  const ys = graph.nodes.map((node) => node.position.y)
  const minX = Math.min(...xs)
  const minY = Math.min(...ys)
  const maxX = Math.max(...xs) + NODE_WIDTH
  const maxY = Math.max(...ys) + NODE_HEIGHT
  const top = includeHeader ? HEADER_HEIGHT : 0
  const width = Math.ceil(maxX - minX + PADDING * 2)
  const height = Math.ceil(maxY - minY + PADDING * 2 + top)
  const offsetX = PADDING - minX
  const offsetY = PADDING + top - minY
  const positions = new Map(
    graph.nodes.map((node) => [
      node.id,
      { x: node.position.x + offsetX, y: node.position.y + offsetY },
    ]),
  )

  const counts = {
    critical: findings.filter((finding) => finding.severity === 'critical').length,
    warning: findings.filter((finding) => finding.severity === 'warning').length,
    info: findings.filter((finding) => finding.severity === 'info').length,
  }

  const parts: string[] = []
  parts.push(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" font-family="Inter, ui-sans-serif, system-ui, sans-serif">`,
    '<defs>',
    `<pattern id="dots" width="24" height="24" patternUnits="userSpaceOnUse"><circle cx="1" cy="1" r="1" fill="#202a36" opacity="0.65"/></pattern>`,
    `<marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M 0 0 L 10 5 L 0 10 z" fill="#46545f"/></marker>`,
    '</defs>',
    `<rect width="${width}" height="${height}" fill="#07090c"/>`,
    `<rect width="${width}" height="${height}" fill="url(#dots)"/>`,
  )

  if (includeHeader) {
    parts.push(
      `<text x="${PADDING}" y="40" fill="#f5f7fa" font-size="20" font-weight="700">${escapeXml(modelName(model))}</text>`,
      `<text x="${PADDING}" y="66" fill="#8b98a9" font-size="12">${model.services.length} services · ${counts.critical} critical · ${counts.warning} warnings · ${counts.info} info · generated by ComposeMap</text>`,
      `<line x1="${PADDING}" y1="${HEADER_HEIGHT - 18}" x2="${width - PADDING}" y2="${HEADER_HEIGHT - 18}" stroke="#1c2530" />`,
    )
  }

  for (const edge of graph.edges) {
    const source = positions.get(edge.source)
    const target = positions.get(edge.target)
    if (!source || !target) continue
    const x1 = source.x + NODE_WIDTH
    const y1 = source.y + NODE_HEIGHT / 2
    const x2 = target.x
    const y2 = target.y + NODE_HEIGHT / 2
    const curve = Math.max(50, Math.abs(x2 - x1) * 0.45)
    const labelX = (x1 + x2) / 2
    const labelY = (y1 + y2) / 2 - 6
    parts.push(
      `<path d="M ${x1} ${y1} C ${x1 + curve} ${y1}, ${x2 - curve} ${y2}, ${x2} ${y2}" fill="none" stroke="#3a4652" stroke-width="1.6" marker-end="url(#arrow)"/>`,
      `<text x="${labelX}" y="${labelY}" fill="#7b8798" font-size="9" font-family="JetBrains Mono, ui-monospace, monospace" text-anchor="middle">needs</text>`,
    )
  }

  for (const node of graph.nodes) {
    const position = positions.get(node.id)
    if (!position) continue
    const { service } = node.data
    const nodeCounts = serviceCounts(findings, service.name)
    const accent =
      nodeCounts.critical > 0
        ? SEVERITY_COLOR.critical
        : nodeCounts.warning > 0
          ? SEVERITY_COLOR.warning
          : nodeCounts.info > 0
            ? SEVERITY_COLOR.info
            : '#2a3542'
    const badgeParts: string[] = []
    if (service.ports.length > 0) badgeParts.push(`${service.ports.length} port${service.ports.length === 1 ? '' : 's'}`)
    if (service.volumes.length > 0) badgeParts.push(`${service.volumes.length} volume${service.volumes.length === 1 ? '' : 's'}`)
    if (nodeCounts.critical > 0) badgeParts.push(`${nodeCounts.critical} critical`)
    if (nodeCounts.warning > 0) badgeParts.push(`${nodeCounts.warning} warning${nodeCounts.warning === 1 ? '' : 's'}`)
    if (badgeParts.length === 0) badgeParts.push(service.healthcheck ? 'healthy' : 'reviewed')

    parts.push(
      `<g transform="translate(${position.x}, ${position.y})">`,
      `<rect width="${NODE_WIDTH}" height="${NODE_HEIGHT}" rx="14" fill="#0c1117" stroke="${accent}" stroke-opacity="${accent === '#2a3542' ? 1 : 0.55}" stroke-width="1.5"/>`,
      `<rect width="${NODE_WIDTH}" height="3" rx="1.5" fill="${accent}" opacity="${accent === '#2a3542' ? 0.6 : 1}"/>`,
      `<circle cx="22" cy="30" r="5" fill="${accent}"/>`,
      `<text x="36" y="35" fill="#f5f7fa" font-size="15" font-weight="650">${escapeXml(truncate(service.name, 24))}</text>`,
      `<text x="22" y="58" fill="#8b98a9" font-size="10.5" font-family="JetBrains Mono, ui-monospace, monospace">${escapeXml(truncate(service.image ?? (service.build ? 'build: ' + service.build : 'no image'), 38))}</text>`,
      `<line x1="20" y1="72" x2="${NODE_WIDTH - 20}" y2="72" stroke="#1c2530"/>`,
      `<text x="22" y="92" fill="#6f7c8c" font-size="9.5" letter-spacing="0.08em">${escapeXml(truncate(badgeParts.join('  /  ').toUpperCase(), 44))}</text>`,
      `<text x="22" y="116" fill="#6f7c8c" font-size="9.5">${service.healthcheck ? '✓ healthcheck' : '○ no healthcheck'}   ${service.restart ? `↻ restart: ${escapeXml(service.restart)}` : '○ no restart'}</text>`,
      '</g>',
    )
  }

  parts.push('</svg>')
  return parts.join('\n')
}

export function toJsonReport(model: ComposeModel, analysis: Analysis): string {
  return `${JSON.stringify(
    {
      tool: 'compose-map',
      version: 1,
      name: modelName(model),
      source: model.sourceName ?? null,
      summary: analysis.stats,
      counts: analysis.counts,
      services: model.services.map((service) => ({
        name: service.name,
        image: service.image ?? null,
        build: service.build ?? null,
        ports: service.ports.map((port) => port.raw),
        volumes: service.volumes.map((volume) => volume.raw),
        environment: Object.keys(service.environment),
        dependsOn: service.dependsOn,
        networks: service.networks,
        healthcheck: service.healthcheck,
        restart: service.restart ?? null,
        privileged: service.privileged,
      })),
      findings: analysis.findings.map((finding) => ({
        rule: finding.rule,
        severity: finding.severity,
        service: finding.service ?? null,
        title: finding.title,
        detail: finding.detail,
        fix: finding.fix,
      })),
    },
    null,
    2,
  )}\n`
}

export function reportFilename(model: ComposeModel, extension: string): string {
  const name =
    model.name ?? model.sourceName?.replace(/\.ya?ml$/i, '') ?? 'compose'
  const slug = name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
  return `${slug || 'compose'}-report.${extension}`
}

export function downloadText(filename: string, content: string, type: string): void {
  const blob = new Blob([content], { type })
  const url = URL.createObjectURL(blob)
  const anchor = document.createElement('a')
  anchor.href = url
  anchor.download = filename
  document.body.append(anchor)
  anchor.click()
  anchor.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}

export async function downloadSvgAsPng(
  filename: string,
  svg: string,
  scale = 2,
): Promise<void> {
  const blob = new Blob([svg], { type: 'image/svg+xml;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  try {
    const image = new Image()
    image.decoding = 'sync'
    await new Promise<void>((resolve, reject) => {
      image.onload = () => resolve()
      image.onerror = () => reject(new Error('Could not render the SVG export.'))
      image.src = url
    })
    const width = image.naturalWidth || 1200
    const height = image.naturalHeight || 800
    const canvas = document.createElement('canvas')
    canvas.width = Math.ceil(width * scale)
    canvas.height = Math.ceil(height * scale)
    const context = canvas.getContext('2d')
    if (!context) throw new Error('Canvas is not available in this browser.')
    context.scale(scale, scale)
    context.drawImage(image, 0, 0)
    const pngBlob = await new Promise<Blob | null>((resolve) =>
      canvas.toBlob(resolve, 'image/png'),
    )
    if (!pngBlob) throw new Error('Could not encode the PNG.')
    const pngUrl = URL.createObjectURL(pngBlob)
    const anchor = document.createElement('a')
    anchor.href = pngUrl
    anchor.download = filename
    document.body.append(anchor)
    anchor.click()
    anchor.remove()
    setTimeout(() => URL.revokeObjectURL(pngUrl), 1000)
  } finally {
    URL.revokeObjectURL(url)
  }
}
